// კალიგრაფიული წარწერა ხმლის პირზე: საკუთარი „ანბანი“ — ძველი ქართული ასომთავრულისა და ელფური დამწერლობის შთაგონებით.
// ყოველი ასო 8×12 ბადეშია (x: -4..4, y: -6..6) და ხაზით (stroke) იხატება, ამიტომ ნებისმიერ ზომაზე სუფთად ჩანს.
// მხოლოდ აბსოლუტური M / L / Q ბრძანებები — წერტილები პირდაპირ გარდაიქმნება და მთელი სვეტი ერთ path-ად ერთიანდება.
import { P, rng } from './utils.js';

export const GLYPHS = [
  'M-3,-6 L-3,6 M-3,-1 Q2,-1 3,-6 M-3,0 Q2,1 3,6',
  'M-3,6 Q-4,-6 0,-6 Q4,-6 3,0 Q2,4 -1,3',
  'M0,-6 L0,6 M-3,-3 Q0,-1 3,-3 M-3,3 Q0,1 3,3',
  'M-3,-5 Q3,-5 0,0 Q-3,5 3,5',
  'M-3,6 L0,-6 L3,6 M-2,1 L2,1',
  'M3,-5 Q-3,-6 -3,0 Q-3,6 3,5 M0,0 L3,0',
  'M-3,-6 L3,-6 M0,-6 L0,2 Q0,6 -3,5',
  'M-3,-6 Q3,0 -3,6 M3,-6 Q-3,0 3,6',
  'M0,-6 Q-4,-2 0,0 Q4,2 0,6 M-3,0 L-1.5,0 M1.5,0 L3,0',
  'M-3,6 L-3,-2 Q-3,-6 0,-6 Q3,-6 3,-2 L3,6',
  'M-3,-4 Q0,-7 3,-4 M0,-5 L0,6 M-2,6 L2,6',
  'M-3,-6 L3,-1 L-3,4 M2,5 L3,6',
  'M-2,-6 Q3,-6 3,-2 Q3,2 -1,2 L3,6 M-2,-6 L-2,6',
  'M3,-6 Q-4,-4 0,0 Q4,4 -3,6 M-1,-7 L1,-7'
];
// ასოს გადატანა: (cx, cy) — ცენტრი, k — ზომა, a — კუთხე (რადიანი; ტექსტის მიმართულება), slant — დახრა (კალიგრაფიული „კურსივი“)
const place = (d, cx, cy, k, a = 0, slant = -.22) => {
  const c = Math.cos(a), s = Math.sin(a);
  return d.replace(/(-?\d*\.?\d+),(-?\d*\.?\d+)/g, (_, x, y) => {
    const lx = (+x + +y * slant) * k, ly = +y * k;
    return `${P(cx + lx * c - ly * s)},${P(cy + lx * s + ly * c)}`;
  });
};

// ჩაჭრილი წარწერა ხაზის გასწვრივ (როგორც ნამდვილ ხმალზე — ჯვარედინასთან, პირის სიგრძეზე): (x0, y0) → (x1, y1).
// ასოები მჭიდროდ, სიტყვებად (3–6 ასო), სიტყვებს შორის — ცარიელი ადგილი. k — ასოს ზომა.
// აბრუნებს ერთ path-ის d-ს; შემთხვევითი ასოები seed-ით — ყოველთვის ერთნაირი
export function runeLine(x0, y0, x1, y1, k, seed) {
  const r = rng(seed), a = Math.atan2(y1 - y0, x1 - x0), len = Math.hypot(x1 - x0, y1 - y0), step = 7 * k;
  let d = '', at = step / 2, left = 3 + Math.floor(r() * 4);
  while (at + step / 2 <= len) {
    d += ' ' + place(GLYPHS[Math.floor(r() * GLYPHS.length)], x0 + Math.cos(a) * at, y0 + Math.sin(a) * at, k, a);
    at += step;
    if (--left === 0) { at += 5 * k; left = 3 + Math.floor(r() * 4); }   // სიტყვებს შორის ადგილი
  }
  return d.trim();
}
